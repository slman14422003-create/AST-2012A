package com.ast2012a.clinicalmaster;

import java.util.Locale;

/**
 * فلتر اختيار نموذج الذكاء الاصطناعي المناسب من بين نماذج Cloudflare
 * Workers AI المتاحة على نفس الووركر الثابت (AiClient.FIXED_WORKER_URL) -
 * بدون أي تغيير في الرابط نفسه ولا في مفتاح API. القرار هنا محلي بالكامل
 * (بدون أي نداء شبكة إضافي) ومبني على طبيعة كل استدعاء:
 *
 * 1) التصنيف (Router): استدعاء خفيف جدًا (كلمة أو كلمتين فقط)، الأهم فيه
 *    السرعة لا العمق - يُستخدم نموذج سريع وخفيف.
 * 2) الدردشة العادية (تحية، سؤال عام، شكر...): لا حاجة لأقصى دقة ممكنة -
 *    نموذج سريع وخفيف يكفي ويقلل زمن الانتظار على المستخدم.
 * 3) المسار الإكلينيكي/الطبي (تأريض + إجابة فعلية عن حالة/علاج/بروتوكول):
 *    هنا الدقة أهم من السرعة - يُستخدم أقوى نموذج متاح مخصّص لزيادة جودة
 *    الاستدلال والدقة الطبية، حتى لو استغرق وقتًا أطول قليلًا.
 * طبقة أمان إضافية: حتى لو صنّف الراوتر رسالة ما CHAT خطأً، mentionsMedicalContent
 * بتفحص محتوى الرسالة نفسها عن كلمات دالة على مضمون طبي/علاجي فعلي، ولو
 * وجدت بترفع مستوى النموذج المستخدم في الدردشة نفسها للنموذج الطبي الأدق
 * بدل الاكتفاء بالنموذج السريع - عشان لو حصل خطأ تصنيف، النموذج المستخدم
 * فعليًا يفضل مناسب لخطورة الموضوع.
 *
 * ملحوظة توافق: اسم الحقل المرسَل هو "model" (يُضاف لجسم JSON بجانب
 * "system" و"message" الحاليين في AiClient). لو الووركر الحالي (worker.js)
 * مش قاريه أو مش بيدعم اختيار نموذج ديناميكي، بيتجاهله بأمان تام (حقل
 * إضافي غير معروف في JSON) والسلوك يفضل كما هو بدون أي كسر - الميزة دي
 * إضافية بحتة (Progressive Enhancement)، مش شرط لعمل التطبيق.
 */
final class AiModelSelector {

    private AiModelSelector() {}

    // نماذج Cloudflare Workers AI المرشحة (أسماء الكتالوج الرسمية). لو
    // الووركر عايز يفعّل اختيار النموذج ديناميكيًا، يقرأ حقل "model" من
    // جسم الطلب ويمرره لـ env.AI.run(model, ...) بدل الاسم الثابت الحالي.

    /** نموذج سريع وخفيف: للتصنيف الأولي (Router) وللدردشة العادية اللي
     *  مفيهاش مضمون طبي فعلي - أولوية السرعة على أقصى دقة ممكنة. */
    static final String MODEL_FAST = "@cf/meta/llama-3.1-8b-instruct";

    /** أقوى نموذج متاح: للمسار الإكلينيكي (تأريض + بروتوكولات + تشخيص
     *  تفريقي) ولأي دردشة تحتوي فعليًا مضمونًا طبيًا/علاجيًا - أولوية الدقة
     *  والاستدلال على السرعة، لتقليل احتمال الهلوسة في سياق طبي حسّاس. */
    static final String MODEL_CLINICAL = "@cf/meta/llama-3.3-70b-instruct";

    /** كلمات دالة على مضمون طبي/علاجي فعلي - طبقة أمان تكميلية لقرار
     *  الراوتر نفسه (مش بديلة عنه): تُستخدم فقط لرفع مستوى النموذج في
     *  مسار الدردشة لو ظهرت إشارة طبية واضحة رغم تصنيفه CHAT. */
    private static final String[] MEDICAL_HINTS = {
            "ألم", "وجع", "علاج", "تمرين", "تمارين", "بروتوكول", "تشخيص",
            "إصابة", "اصابة", "عضلة", "عضلات", "مفصل", "مفاصل", "عصب", "أعصاب",
            "تأهيل", "جلسة", "جلسات", "مريض", "مرضى", "كهربائي", "تحفيز",
            "خزل", "شلل", "انزلاق", "غضروف", "التهاب", "كسر", "جبيرة",
            "فقرات", "عمود فقري", "ركبة", "كتف", "ظهر", "رقبة", "قدم",
            "TENS", "EMS", "فيزيوثيرابي", "علاج طبيعي", "عرق النسا"
    };

    /** يفحص لو نص المستخدم فيه إشارة طبية/علاجية فعلية - مطابقة بسيطة
     *  بالكلمات (بدون حساسية لحالة الأحرف بالنسبة للإنجليزي). */
    static boolean mentionsMedicalContent(String text) {
        if (text == null || text.trim().isEmpty()) return false;
        String t = text.toLowerCase(Locale.ROOT);
        for (String hint : MEDICAL_HINTS) {
            if (t.contains(hint.toLowerCase(Locale.ROOT))) return true;
        }
        return false;
    }

    /** النموذج المستخدم لاستدعاء التصنيف الخفيف (Router) - دايمًا السريع،
     *  لأن المطلوب منه رد قصير جدًا (سطر أو سطرين) بأقل زمن ممكن. */
    static String forRouter() {
        return MODEL_FAST;
    }

    /** النموذج المستخدم لمسار الدردشة العادية - سريع افتراضيًا، إلا لو
     *  الرسالة نفسها فيها مضمون طبي واضح (طبقة أمان لو أخطأ التصنيف). */
    static String forChat(String userText) {
        return mentionsMedicalContent(userText) ? MODEL_CLINICAL : MODEL_FAST;
    }

    /** النموذج المستخدم للمسار الإكلينيكي الكامل (تأريض + إجابة نهائية،
     *  بما فيها كل محاولات الاستكمال التلقائي) - دايمًا الأدق، لأن هذا
     *  المسار هو اللي بيحمل فعليًا توصيات علاجية/موانع استطباب. */
    static String forClinical() {
        return MODEL_CLINICAL;
    }
}
