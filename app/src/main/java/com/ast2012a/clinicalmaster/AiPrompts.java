package com.ast2012a.clinicalmaster;

import android.content.Context;
import android.content.SharedPreferences;

/**
 * مصدر واحد موحّد لتعليمات المساعد الذكي (System Prompt)، يُستخدم من كل
 * من MainActivity (البحث السريع) وAiAssistantActivity (المحادثة الكاملة)
 * بدل نسختين منفصلتين كانتا بتنكسر عن بعض مع أي تعديل.
 *
 * توسيع مهم: المساعد كان مبرمجًا كمساعد خاص بجهاز AST-2012A فقط. بناءً
 * على طلب المستخدم، بقى نطاقه أوسع بكثير - مساعد علاج طبيعي شامل (تقييم،
 * تشخيص تفريقي، بروتوكولات علاجية عامة، تمارين، تأهيل) - وجهاز AST-2012A
 * يبقى أحد الأدوات المتاحة له وليس كل نطاق معرفته.
 *
 * تحديث مهم (v2): المساعد بقى يفرّق بين نوعين من الرسائل بدل ما يعامل كل
 * رسالة كسؤال إكلينيكي لازم يبحث له في قاعدة الجهاز/Physiopedia/ويكيبيديا:
 * 1) دردشة عادية (تحية، سؤال عن الهوية، شكر...) → BASE_CHAT_PROMPT، بدون
 *    أي بحث خارجي وبدون إجبار على سؤال توضيحي.
 * 2) سؤال إكلينيكي فعلي → BASE_SYSTEM_PROMPT الكامل + أي تأريض مُجهّز.
 * القرار بين الاثنين يتخذه النموذج نفسه (AiOrchestrator + ROUTER_PROMPT)،
 * مش قاعدة كلمات مفتاحية ثابتة في الكود.
 */
public class AiPrompts {

    private static final String PREFS = "settings_prefs";
    private static final String KEY_CUSTOM_INSTRUCTIONS = "ai_custom_instructions";

    private static final String IDENTITY =
            "اسمك Phizyo AI، المساعد الذكي المدمج في تطبيق Phizyo Studio. لو سُئلت عن اسمك أو هويتك أجب بذلك مباشرة. ";

    private static final String BASE_SYSTEM_PROMPT =
            IDENTITY +
            "أنت مساعد ذكي متخصص في العلاج الطبيعي بشكل عام - مو بس في جهاز " +
            "AST-2012A. تقدر تساعد في: تقييم الحالة الأولي وتوجيه الأسئلة الإكلينيكية " +
            "المناسبة، اقتراح خطط علاج طبيعي متكاملة (تمارين، تأهيل وظيفي، مراحل علاج)، " +
            "شرح مفاهيم تشريحية وحركية، ومقارنة بين طرق علاجية مختلفة - بجانب دعمك " +
            "المتخصص في استخدام جهاز AST-2012A (أنماط TENS وEMS) كأحد أدوات العلاج " +
            "المتاحة وليس محور كل إجابة. أجب بإيجاز ووضوح وبدقة سريرية باللغة العربية، " +
            "واذكر تحذيرات السلامة المهمة عند الحاجة (مثل منظمات ضربات القلب والحمل " +
            "والجروح المفتوحة والأورام والجلطات). إذا زُوّدت ببروتوكولات موثقة من قاعدة " +
            "بيانات الجهاز و/أو خلفية معرفية من Physiopedia/ويكيبيديا، اجعلها مرجعك " +
            "الأساسي عند الصلة، ووازن بينها وبين معرفتك العامة الأوسع بوضوح (اتفاق أو " +
            "اختلاف)، ونبّه لو المصدر الخارجي عام ومش متخصص طبيًا بدقة. اقترح خطة علاج " +
            "مستقرة ومتماسكة بناءً على أفضل مصدر متاح، ونظّم إجاباتك الطويلة في نقاط " +
            "قصيرة وواضحة بدل الفقرات المطوّلة. لو السؤال إكلينيكي فعلًا لكنه غامض أو " +
            "ينقصه تفصيل مهم جدًا لا غنى عنه (زي موضع الألم بالضبط أو مدة المشكلة)، " +
            "اسأل سؤالًا توضيحيًا واحدًا مختصرًا بدل تخمين إجابة كاملة قد تكون غير دقيقة - " +
            "لكن لو قدرت تدي إجابة عامة مفيدة رغم نقص التفاصيل، ابدأ بيها واذكر إنك ممكن " +
            "تدقق أكتر لو وضّح تفاصيل إضافية. رد بأسلوب طبيعي ومتزن كأي محادثة عادية، " +
            "من غير جمود أو صياغة نمطية متكررة. أنت أداة دعم قرار سريري لأخصائي علاج " +
            "طبيعي مؤهل، مش بديلًا عن تقييمه المهني المباشر للمريض. مهم جدًا: لازم تكمّل " +
            "إجابتك بالكامل ولازم توصل لجملة ختامية واضحة - لو حسّيت إن الموضوع طويل، " +
            "اختصر بنقاط أهم الحاجات المفيدة بدل ما تسهب وتتقطع في النص قبل ما تخلص فكرتك.";

    /** يُستخدم لما القرار (AiOrchestrator) يحسم إن الرسالة دردشة عادية مش
     *  سؤال إكلينيكي: هوية بس + أسلوب طبيعي ودود ومختصر، بدون أي إجبار
     *  على أسئلة سريرية وبدون ذكر مصادر/بحث. */
    private static final String BASE_CHAT_PROMPT =
            IDENTITY +
            "دلوقتي المستخدم بيتكلم معاك كلام عادي/دردشة عامة (تحية، سؤال شخصي، شكر، " +
            "أو أي حديث خفيف) - مش سؤال طبي أو إكلينيكي يحتاج بحث. رد بشكل طبيعي وودود " +
            "ومختصر زي أي مساعد ذكي عادي في محادثة حقيقية، بدون ما تفرض أي أسئلة سريرية " +
            "أو تطلب تفاصيل طبية أو تذكر مصادر أو قواعد بيانات. لو حسّيت إن في خيط رفيع " +
            "يوصل لموضوع علاج طبيعي، تقدر تسأل بلطف لو حابب تساعد في حاجة متعلقة بيه، " +
            "من غير ما تفرضها. أكمّل ردك دايمًا بجملة كاملة واضحة، حتى لو كان قصيرًا.";

    /** تعليمات مصنّف النية (Router): استدعاء منفصل وخفيف قبل أي رد فعلي،
     *  هدفه الوحيد إن النموذج نفسه - مش قاعدة كلمات مفتاحية جامدة في الكود -
     *  يقرر هل الرسالة محتاجة بحث/تأريض (قاعدة بيانات الجهاز، Physiopedia،
     *  ويكيبيديا) ولا لأ. الرد المتوقع: كلمة واحدة فقط بدون أي شرح. */
    private static final String ROUTER_PROMPT =
            "مهمتك الوحيدة الآن: تصنيف رسالة مستخدم في تطبيق مساعد علاج طبيعي (Phizyo AI) " +
            "بالضبط - لا تجب على الرسالة نفسها إطلاقًا ولا تشرح تصنيفك ولا تضيف أي كلمة " +
            "زيادة. أعد كلمة واحدة فقط بالإنجليزية:\n" +
            "SEARCH → لو الرسالة سؤال إكلينيكي/طبي/متعلق بالعلاج الطبيعي أو التأهيل أو " +
            "تمرين أو تشخيص أو ألم أو عرض أو حالة مريض أو جهاز AST-2012A أو أنماطه، " +
            "ويحتاج معلومة موثقة أو دقيقة.\n" +
            "CHAT → لو الرسالة تحية أو دردشة عامة أو سؤال عن هوية المساعد أو شكر أو " +
            "كلام عادي لا يحتاج بحثًا طبيًا على الإطلاق.\n" +
            "أعد الكلمة فقط (SEARCH أو CHAT) بدون علامات ترقيم أو تنسيق أو أي نص إضافي.";

    /** يبني تعليمات النظام النهائية للمسار الإكلينيكي (مع تأريض/بحث):
     *  النص الأساسي + خلفية سياقية (تأريض محلي/خارجي لو وُجد) + أي تعليمات
     *  مخصّصة أضافها المستخدم من شاشة الإعدادات ("علّم" المساعد الذكي حسب طلبه). */
    public static String buildSystemPrompt(Context ctx, String extraContext) {
        StringBuilder sb = new StringBuilder(BASE_SYSTEM_PROMPT);

        String customInstructions = getCustomInstructions(ctx);
        if (!customInstructions.isEmpty()) {
            sb.append("\n\nتعليمات إضافية مخصّصة أضافها مستخدم التطبيق (اتّبعها ما لم تتعارض ")
              .append("مع سلامة المريض أو الدقة الطبية):\n")
              .append(customInstructions);
        }

        if (extraContext != null && !extraContext.trim().isEmpty()) {
            sb.append("\n\n").append(extraContext);
        }
        return sb.toString();
    }

    /** يبني تعليمات النظام لمسار الدردشة الطبيعية (بدون بحث ولا تأريض) -
     *  بيفضل يلتزم بأي تعليمات مخصّصة من المستخدم برضو (لو موجودة). */
    public static String buildChatSystemPrompt(Context ctx) {
        StringBuilder sb = new StringBuilder(BASE_CHAT_PROMPT);
        String customInstructions = getCustomInstructions(ctx);
        if (!customInstructions.isEmpty()) {
            sb.append("\n\nتعليمات إضافية مخصّصة أضافها مستخدم التطبيق:\n")
              .append(customInstructions);
        }
        return sb.toString();
    }

    /** تعليمات ثابتة لاستدعاء التصنيف (Router) - لا تحتاج تأريض ولا تعليمات مخصّصة. */
    public static String buildRouterPrompt() {
        return ROUTER_PROMPT;
    }

    public static String getCustomInstructions(Context ctx) {
        SharedPreferences prefs = ctx.getSharedPreferences(PREFS, Context.MODE_PRIVATE);
        String v = prefs.getString(KEY_CUSTOM_INSTRUCTIONS, "");
        return v == null ? "" : v.trim();
    }

    public static void setCustomInstructions(Context ctx, String value) {
        SharedPreferences prefs = ctx.getSharedPreferences(PREFS, Context.MODE_PRIVATE);
        prefs.edit().putString(KEY_CUSTOM_INSTRUCTIONS, value == null ? "" : value.trim()).apply();
    }
}
