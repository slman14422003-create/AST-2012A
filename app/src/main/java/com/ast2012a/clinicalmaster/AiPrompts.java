    /** يستخرج مصطلح البحث الإنجليزي (لو موجود) من رد المصنّف (Router) لما
     *  يقرر SEARCH: السطر الثاني من الرد لو موجود وغير فاضٍ بعد التقليم،
     *  وإلا null (يخلي الطرف المستدعي يرجع للسلوك القديم - البحث بنص
     *  السؤال الأصلي كما هو). */
    public static String extractSearchTerm(String decision) {
        if (decision == null) return null;
        int nl = decision.indexOf('\n');
        if (nl < 0) return null;
        String term = decision.substring(nl + 1).trim();
        return term.isEmpty() ? null : term;
    }

    public static String getCustomInstructions(Context ctx) {
        SharedPreferences prefs = ctx.getSharedPreferences(PREFS, Context.MODE_PRIVATE);
        String v = prefs.getString(KEY_CUSTOM_INSTRUCTIONS, "");
        return v == null ? "" : v.trim();
    }

    public static void setCustomInstructions(Context ctx, String value) {
        SharedPreferences prefs = ctx.getSharedPreferences(PREFS, Context.MODE_PRIVATE);
        prefs.edit().putString(KEY_CUSTOM_INSTRUCTIONS, value == null ? "" : value.trim()).apply();
    }
